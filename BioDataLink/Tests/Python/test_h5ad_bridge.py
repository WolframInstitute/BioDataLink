"""Optional H5AD integration tests; requires the explicit AnnData test environment.

Run: <python> -m unittest discover -s BioDataLink/Tests/Python -v
Expected matrices below are independently specified, not reconstructed by the reader.
"""
import importlib.util
import io
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
import warnings

import anndata as ad
import h5py
import numpy as np
import pandas as pd
import scipy.sparse as sp

BRIDGE = Path(__file__).resolve().parents[2] / "Assets/Python/h5ad_bridge.py"
spec = importlib.util.spec_from_file_location("h5ad_bridge", BRIDGE)
bridge = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bridge)
bridge.h5py, bridge.np = h5py, np

MATRIX = np.array([[0, 2, 0, 5], [7, 0, 11, 0], [9007199254740993, 0, 0, 17]], dtype=np.int64)


def write_fixture(path, matrix_format="csr"):
    """The bundled toy-anndata.h5ad is generated by this same explicit fixture."""
    obs = pd.DataFrame({"kind": pd.Categorical(["T", None, "B"], categories=["T", "B"], ordered=True),
                        "donor": pd.array([1, None, 3], dtype="Int64"),
                        "flag": pd.array([True, None, False], dtype="boolean"),
                        "note": pd.array(["alpha", None, "beta"], dtype="string"),
                        "ID": ["source-A", "source-B", "source-C"]}, index=["c0", "c1", "c2"])
    var = pd.DataFrame({"symbol": ["A", "B", "C", "D"]}, index=["g1", "g1", "g3", "g4"])
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", UserWarning)
        warnings.filterwarnings("ignore", message="The 'future.infer_string' option is deprecated.*", module="anndata.*")
        constructor = {"csr": sp.csr_matrix, "csc": sp.csc_matrix, "dense": np.array}[matrix_format]
        data = ad.AnnData(constructor(MATRIX), obs=obs, var=var)
        data.layers["normalized"] = sp.csc_matrix([[0, .2, 0, .5], [.7, 0, 1.1, 0], [1.3, 0, 0, 1.7]])
        data.raw = ad.AnnData(sp.csr_matrix(np.column_stack([MATRIX, [19, 23, 29]])),
                             obs=obs.copy(), var=pd.DataFrame(index=["r1", "r2", "r3", "r4", "r5"]))
        data.obsm["X_umap"] = np.array([[1., 2.], [3., 4.], [5., 6.]])
        data.uns["note"] = "Synthetic fixture; not biological observations."
        data.write_h5ad(path)


def request(path, **options):
    return {"SourceFile": str(path), "Cells": None, "Genes": None, "Layer": "X",
            "MaxSelectedElements": 10_000_000, "MaxTransferBytes": 67_108_864,
            "MaxFileBytes": 10_000_000} | options


def project(path, **options):
    stream = io.BytesIO()
    bridge.read_projection(request(path, **options), stream)
    return json.loads(stream.getvalue())


def dense(result):
    rows = [[0] * result["Shape"][1] for _ in range(result["Shape"][0])]
    for row, column, value in result["Entries"]:
        rows[row - 1][column - 1] = value
    return rows


class AnnDataBridge(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.path = Path(self.directory.name) / "synthetic.h5ad"
        write_fixture(self.path)

    def tearDown(self):
        self.directory.cleanup()

    def assert_tag(self, tag, **options):
        with self.assertRaises(bridge.ReadError) as raised:
            project(self.path, **options)
        self.assertEqual(raised.exception.tag, tag)

    def test_dense_csr_csc_order_axes_and_exact_large_integer(self):
        for encoding in ("csr", "csc", "dense"):
            with self.subTest(encoding=encoding):
                write_fixture(self.path, encoding)
                result = project(self.path, Cells=[3, 1], Genes=[4, 1, 2])
                self.assertEqual(dense(result), [[17, 9007199254740993, 0], [5, 0, 2]])
                self.assertEqual([x["ID"] for x in result["GeneMetadata"]], ["g4", "g1", "g1"])
                self.assertEqual(result["SelectedCells"], [3, 1])
                self.assertEqual(result["SelectedGenes"], [4, 1, 2])
                with warnings.catch_warnings():
                    warnings.simplefilter("ignore", UserWarning)
                    warnings.filterwarnings("ignore", message="The 'future.infer_string' option is deprecated.*", module="anndata.*")
                    independent = ad.read_h5ad(self.path)
                values = independent.X.toarray() if sp.issparse(independent.X) else independent.X
                self.assertEqual(values.tolist(), MATRIX.tolist())

    def test_category_nullable_annotations_and_name_collision(self):
        result = project(self.path, Cells=[2, 1])
        missing = result["CellMetadata"][0]["Annotations"]
        self.assertEqual([missing[x] for x in ("kind", "donor", "flag", "note")], [None] * 4)
        self.assertEqual(missing["ID"], "source-B")
        self.assertEqual(result["CellMetadata"][0]["ID"], "c1")
        self.assertTrue(result["CellMetadataEncoding"]["kind"]["Ordered"])
        self.assertEqual(result["CellMetadataEncoding"]["kind"]["CategoryCount"], 2)
        self.assertEqual(result["CellMetadataEncoding"]["kind"]["SelectedCategories"],
                         [{"SourceIndex": 1, "Value": "T"}])

    def test_sparse_shape_requires_actual_integers(self):
        with h5py.File(self.path, "a") as file:
            file["X"].attrs["shape"] = [3.5, 4.0]
        self.assert_tag("InvalidAnnData")

    def test_nullable_encoding_must_match_value_dtype(self):
        with h5py.File(self.path, "a") as file:
            file["obs/donor"].attrs["encoding-type"] = "nullable-boolean"
        self.assert_tag("InvalidAnnData")

    def test_layer_and_raw_gene_axis(self):
        layer = project(self.path, Layer=["Layers", "normalized"], Cells=[2, 1], Genes=[3, 2])
        self.assertEqual(dense(layer), [[1.1, 0], [0, .2]])
        self.assertIn("X", layer["OmittedStructures"])
        self.assertNotIn("layers/normalized", layer["OmittedStructures"])
        raw = project(self.path, Layer=["Raw", "X"], Cells=[3, 1], Genes=[5, 2])
        self.assertEqual(dense(raw), [[29, 0], [19, 2]])
        self.assertEqual(raw["SourceShape"], [3, 5])
        self.assertEqual([x["ID"] for x in raw["GeneMetadata"]], ["r5", "r2"])
        self.assertIn("var", raw["OmittedStructures"])

    def test_limits_before_matrix_read_and_transfer_cap(self):
        self.assert_tag("SelectionTooLarge", MaxSelectedElements=11)
        self.assert_tag("FileTooLarge", MaxFileBytes=1)
        self.assert_tag("TransferTooLarge", MaxTransferBytes=100)
        self.assert_tag("InvalidSelection", Cells=[1, 1])
        self.assert_tag("InvalidSelection", Genes=[5])
        self.assert_tag("InvalidSelection", Cells=[])

    def test_nonfinite_selected_measurements_are_not_zero_filled(self):
        write_fixture(self.path, "dense")
        with h5py.File(self.path, "a") as file:
            del file["X"]
            matrix = file.create_dataset("X", data=np.array([[np.nan, 2., 0., 5.], [7., 0., 11., 0.], [13., 0., 0., 17.]]))
            matrix.attrs.update({"encoding-type": "array", "encoding-version": "0.2.0"})
        self.assert_tag("MissingMeasurement")
        self.assertEqual(dense(project(self.path, Cells=[2], Genes=[1])), [[7.]])

    def test_external_and_soft_links_refused(self):
        for link in (h5py.ExternalLink("never-opened.h5", "X"), h5py.SoftLink("/raw/X")):
            with self.subTest(link=type(link).__name__):
                write_fixture(self.path)
                with h5py.File(self.path, "a") as file:
                    del file["X"]
                    file["X"] = link
                self.assert_tag("UnsupportedHDF5Link")

    def test_unknown_matrix_encoding_and_sparse_duplicate(self):
        with h5py.File(self.path, "a") as file:
            file["X"].attrs["encoding-version"] = "9.0.0"
        self.assert_tag("UnsupportedMatrixEncoding")
        write_fixture(self.path)
        with h5py.File(self.path, "a") as file:
            file["X/indices"][1] = file["X/indices"][0]
        self.assert_tag("DuplicateCoordinates")

    def test_cli_result_is_structured_and_bounded_on_failure(self):
        input_file = Path(self.directory.name) / "request.json"
        output_file = Path(self.directory.name) / "response.json"
        input_file.write_text(json.dumps(request(self.path, MaxTransferBytes=1000)))
        completed = subprocess.run([sys.executable, str(BRIDGE), str(input_file), str(output_file)],
                                   capture_output=True, timeout=10, check=True)
        self.assertEqual(completed.stdout, b"")
        result = json.loads(output_file.read_text())
        self.assertEqual(result["Tag"], "TransferTooLarge")
        self.assertLess(output_file.stat().st_size, 1000)

    def test_missing_optional_dependencies_are_reported_without_installation(self):
        output_file = Path(self.directory.name) / "response.json"
        subprocess.run([sys.executable, "-S", str(BRIDGE), "unused-request.json", str(output_file)],
                       capture_output=True, timeout=10, check=True)
        self.assertEqual(json.loads(output_file.read_text())["Tag"], "MissingPythonDependency")


if __name__ == "__main__":
    unittest.main()
